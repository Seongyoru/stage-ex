#!/usr/bin/env node
// Generates src/core/spec.js from research/model-spec.json: the same numbers, with the
// per-field confidence notes (_conf) stripped so the runtime bundle stays small.
// The research JSON remains the annotated source of truth; re-run after editing it:
//   node tools/build-spec.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(resolve(root, 'research/model-spec.json'), 'utf8'));

const strip = (o) => {
  if (Array.isArray(o)) return o.map(strip);
  if (o && typeof o === 'object') {
    const r = {};
    for (const [k, v] of Object.entries(o)) if (k !== '_conf') r[k] = strip(v);
    return r;
  }
  return o;
};

const spec = strip(src);
const header = `// GENERATED by tools/build-spec.mjs from research/model-spec.json — do not edit by hand.
// Parametric specification of K-Arena Yokohama (metres, degrees; heights above the arena floor).
// Field provenance and confidence (CONFIRMED / REPORTED / ESTIMATED) live in the research JSON.
//
// Frames used by field-name suffix (convert with src/core/frame.js):
//   *_G  geo-arena frame: origin = centre of the stage-end outer wall, +Y toward the rear,
//        +X toward house-LEFT (north-east).            world = G(x, y)  → [−x, y − 34.7]
//   *_H  hall frame: same axes, origin = stage-front centre. world = H(x, y)  → [−x, y]
//   The three.js WORLD frame has +X = house-RIGHT, so X always flips sign.
`;
writeFileSync(resolve(root, 'src/core/spec.js'), `${header}export const SPEC = ${JSON.stringify(spec, null, 1)};\n\nexport default SPEC;\n`);
console.log('src/core/spec.js written:', Object.keys(spec).length, 'sections');
